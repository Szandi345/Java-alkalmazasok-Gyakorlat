USE `dillsz`;

CREATE TABLE IF NOT EXISTS suti (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    nev VARCHAR(150) NOT NULL,
    tipus VARCHAR(100) NOT NULL,
    dijazott BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_hungarian_ci;

CREATE TABLE IF NOT EXISTS tartalom (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    sutiid INT UNSIGNED NOT NULL,
    mentes VARCHAR(50) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_tartalom_suti
        FOREIGN KEY (sutiid) REFERENCES suti(id)
        ON UPDATE CASCADE
        ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_hungarian_ci;

CREATE TABLE IF NOT EXISTS ar (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    sutiid INT UNSIGNED NOT NULL,
    ertek DECIMAL(10,2) NOT NULL,
    egyseg VARCHAR(50) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_ar_suti
        FOREIGN KEY (sutiid) REFERENCES suti(id)
        ON UPDATE CASCADE
        ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_hungarian_ci;
